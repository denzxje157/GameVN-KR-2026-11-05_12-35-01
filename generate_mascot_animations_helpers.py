def build_anim_clip(name, sprite_guids, sample_rate=8, loop=True):
    stop_time = len(sprite_guids) / sample_rate
    lines = [
        '%YAML 1.1',
        '%TAG !u! tag:unity3d.com,2011:',
        '--- !u!74 &7400000',
        'AnimationClip:',
        '  m_ObjectHideFlags: 0',
        '  m_CorrespondingSourceObject: {fileID: 0}',
        '  m_PrefabInstance: {fileID: 0}',
        '  m_PrefabAsset: {fileID: 0}',
        f'  m_Name: {name}',
        '  serializedVersion: 7',
        '  m_Legacy: 0',
        '  m_Compressed: 0',
        '  m_UseHighQualityCurve: 1',
        '  m_RotationCurves: []',
        '  m_CompressedRotationCurves: []',
        '  m_EulerCurves: []',
        '  m_PositionCurves: []',
        '  m_ScaleCurves: []',
        '  m_FloatCurves: []',
        '  m_PPtrCurves:',
        '  - serializedVersion: 2',
        '    curve:'
    ]
    for idx, sg in enumerate(sprite_guids):
        t = idx / sample_rate
        lines.append(f'    - time: {t:.4f}')
        lines.append(f'      value: {{fileID: 21300000, guid: {sg}, type: 3}}')
    lines.extend([
        '    attribute: m_Sprite',
        '    path: ',
        '    classID: 212',
        '    script: {fileID: 0}',
        '    flags: 2',
        f'  m_SampleRate: {sample_rate}',
        '  m_WrapMode: 0',
        '  m_Bounds:',
        '    m_Center: {x: 0, y: 0, z: 0}',
        '    m_Extent: {x: 0, y: 0, z: 0}',
        '  m_ClipBindingConstant:',
        '    genericBindings:',
        '    - serializedVersion: 2',
        '      path: 0',
        '      attribute: 0',
        '      script: {fileID: 0}',
        '      typeID: 212',
        '      customType: 23',
        '      isPPtrCurve: 1',
        '      isIntCurve: 0',
        '      isSerializeReferenceCurve: 0',
        '    pptrCurveMapping:'
    ])
    for sg in sprite_guids:
        lines.append(f'    - {{fileID: 21300000, guid: {sg}, type: 3}}')
    lines.extend([
        '  m_AnimationClipSettings:',
        '    serializedVersion: 2',
        '    m_AdditiveReferencePoseClip: {fileID: 0}',
        '    m_AdditiveReferencePoseTime: 0',
        '    m_StartTime: 0',
        f'    m_StopTime: {stop_time:.4f}',
        '    m_OrientationOffsetY: 0',
        '    m_Level: 0',
        '    m_CycleOffset: 0',
        '    m_HasAdditiveReferencePose: 0',
        f'    m_LoopTime: {1 if loop else 0}',
        '    m_LoopBlend: 0',
        '    m_LoopBlendOrientation: 0',
        '    m_LoopBlendPositionY: 0',
        '    m_LoopBlendPositionXZ: 0',
        '    m_KeepOriginalOrientation: 0',
        '    m_KeepOriginalPositionY: 1',
        '    m_KeepOriginalPositionXZ: 0',
        '    m_HeightFromFeet: 0',
        '    m_Mirror: 0',
        '  m_EditorCurves: []',
        '  m_EulerEditorCurves: []',
        '  m_HasGenericRootTransform: 0',
        '  m_HasMotionFloatCurves: 0',
        '  m_Events: []'
    ])
    return '\n'.join(lines) + '\n'

